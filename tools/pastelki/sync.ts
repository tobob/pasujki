/**
 * Sync illustrations from Pastelki (https://pastelki.marchew.work), the shared picture library, into the app.
 *
 *   npm run sync-art            # pull every item whose published Pastelki version is newer than the lock
 *   npm run sync-art -- --init  # first run: record the current Pastelki versions as the baseline, download nothing
 *   npm run sync-art -- --dry   # show what would change
 *
 * Link: item id `foo_bar` ↔ Pastelki slug `foo-bar` (the library was seeded from this app).
 * The baseline is what the app draws itself (src/art/items/*.tsx). When a NEWER version is approved in
 * Pastelki, its SVG is written to src/art/library/svgs.ts and <ItemArt> renders it instead of the component.
 * pastelki.lock.json records the synced version + hash of every item, so runs are idempotent.
 *
 * Safety: an update is skipped (and reported) unless the SVG is a plain 100×100 drawing with no scripts,
 * external references or event handlers, and it still contains the item's dominant colour from
 * src/art/dominant.ts as a fill — colour rounds stay fair. Runs daily in .github/workflows/sync-pastelki.yml.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { ITEM_DOMINANT } from '../../src/art/dominant';
import { COLORS, UI } from '../../src/game/palette';

const ROOT = join(__dirname, '../..');
const LOCK = join(ROOT, 'pastelki.lock.json');
const OUT = join(ROOT, 'src/art/library/svgs.ts');
const SOURCE = process.env.PASTELKI_URL ?? 'https://pastelki.marchew.work';
const SIL_FILL = UI.outline;
const SIL_OPACITY = 0.85; // same as kit.tsx SILHOUETTE_OPACITY

type LockItem = { slug: string; version: number; sha256: string; synced: boolean };
type Lock = { source: string; items: Record<string, LockItem> };
type LibItem = { slug: string; version: number; svg_url: string; color_hex: string };
type Entry = { svg: string; silhouette: string; version: number };

const args = new Set(process.argv.slice(2));
const sha = (s: string) => createHash('sha256').update(s).digest('hex');

function problems(svg: string, dominantHex: string): string[] {
  const p: string[] = [];
  if (!/^<svg\b[^>]*viewBox="0 0 100 100"/.test(svg.trim())) p.push('not a viewBox="0 0 100 100" drawing');
  if (/<script|<foreignObject|<image\b|\son[a-z]+\s*=|javascript:|href="(?!#)|url\((?!#)/i.test(svg)) p.push('active or external content');
  if (svg.length > 200_000) p.push('too large');
  if (!new RegExp(`fill="${dominantHex}"`, 'i').test(svg)) p.push(`dominant colour ${dominantHex} missing`);
  return p;
}

/** Flat silhouette for shadow rounds — the same alpha-mask trick as <Art> in kit.tsx. */
function silhouette(svg: string): string {
  const inner = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs>` +
    `<mask id="sil" maskUnits="userSpaceOnUse" x="0" y="0" width="100" height="100" mask-type="alpha" style="mask-type:alpha">${inner}</mask>` +
    `</defs><rect x="0" y="0" width="100" height="100" fill="${SIL_FILL}" opacity="${SIL_OPACITY}" mask="url(#sil)"/></svg>`
  );
}

function readEntries(): Record<string, Entry> {
  if (!existsSync(OUT)) return {};
  const m = readFileSync(OUT, 'utf8').match(/\/\/ DATA\n([\s\S]*?)\n\/\/ END/);
  return m ? JSON.parse(m[1]) : {};
}

function writeEntries(e: Record<string, Entry>) {
  const sorted = Object.fromEntries(Object.entries(e).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(
    OUT,
    `// GENERATED by tools/pastelki/sync.ts from ${SOURCE} — do not edit by hand.\n` +
      `// Items listed here are drawn from the Pastelki library instead of src/art/items/<id>.tsx.\n` +
      `import type { ItemId } from '@/game/types';\n\n` +
      `export type LibrarySvg = { svg: string; silhouette: string; version: number };\n\n` +
      `export const LIBRARY_SVGS: Partial<Record<ItemId, LibrarySvg>> = DATA;\n`.replace(
        'DATA',
        `(\n// DATA\n${JSON.stringify(sorted, null, 1)}\n// END\n) as Partial<Record<ItemId, LibrarySvg>>`,
      ),
  );
}

async function main() {
  const res = await fetch(`${SOURCE}/api/library`);
  if (!res.ok) throw new Error(`library: HTTP ${res.status}`);
  const lib = new Map<string, LibItem>(((await res.json()).items as LibItem[]).map((i) => [i.slug, i]));
  const lock: Lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, 'utf8')) : { source: SOURCE, items: {} };
  const entries = readEntries();
  const report = { updated: [] as string[], skipped: [] as string[], missing: [] as string[] };

  for (const [id, colorId] of Object.entries(ITEM_DOMINANT)) {
    const slug = id.replace(/_/g, '-');
    const item = lib.get(slug);
    if (!item) {
      report.missing.push(id);
      continue;
    }
    const known = lock.items[id];
    if (args.has('--init') && !known) {
      lock.items[id] = { slug, version: item.version, sha256: '', synced: false };
      continue;
    }
    if (known && item.version <= known.version) continue;
    const svg = (await (await fetch(SOURCE + item.svg_url)).text()).trim();
    const bad = problems(svg, COLORS[colorId]);
    if (bad.length) {
      report.skipped.push(`${id} v${item.version}: ${bad.join(', ')}`);
      continue;
    }
    report.updated.push(`${id} v${known?.version ?? '?'} → v${item.version}`);
    if (args.has('--dry')) continue;
    entries[id] = { svg, silhouette: silhouette(svg), version: item.version };
    lock.items[id] = { slug, version: item.version, sha256: sha(svg), synced: true };
  }

  if (!args.has('--dry')) {
    lock.items = Object.fromEntries(Object.entries(lock.items).sort(([a], [b]) => a.localeCompare(b)));
    writeFileSync(LOCK, JSON.stringify(lock, null, 2) + '\n');
    writeEntries(entries);
  }
  console.log(`updated ${report.updated.length}: ${report.updated.join('; ') || '-'}`);
  if (report.skipped.length) console.log(`skipped ${report.skipped.length}:\n  ${report.skipped.join('\n  ')}`);
  if (report.missing.length) console.log(`not in Pastelki (${report.missing.length}): ${report.missing.join(', ')}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
