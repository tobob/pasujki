#!/usr/bin/env node
/** Regenerates src/art/registry.ts (imports of every item/texture file). Run: node tools/art/gen-registry.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const list = (d) => fs.readdirSync(path.join(root, d)).filter((f) => /^[a-z_]+\.tsx$/.test(f)).map((f) => f.slice(0, -4)).sort();
const pascal = (id) => id.split('_').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const items = list('src/art/items');
const textures = list('src/art/textures');
const src = `// GENERATED by tools/art/gen-registry.mjs — do not edit by hand.
// Typed as Record<ItemId|TextureId, …> so a missing or unknown id is a type error.
import type { ComponentType } from 'react';

import type { ItemId, TextureId } from '@/game/types';

${items.map((id) => `import Item${pascal(id)} from './items/${id}';`).join('\n')}

${textures.map((id) => `import Texture${pascal(id)} from './textures/${id}';`).join('\n')}

type ArtComponent = ComponentType<{ size: number }>;

export const ITEMS: Record<ItemId, ArtComponent> = {
${items.map((id) => `  ${id}: Item${pascal(id)},`).join('\n')}
};

export const TEXTURES: Record<TextureId, ArtComponent> = {
${textures.map((id) => `  ${id}: Texture${pascal(id)},`).join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/art/registry.ts'), src);
console.log(`registry: ${items.length} items, ${textures.length} textures`);
